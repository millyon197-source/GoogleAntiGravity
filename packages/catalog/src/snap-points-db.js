/**
 * Retrieve snap points for a given macro name, with fallback to local bounding face centers if needed.
 *
 * @param {string} macroName X4 module macro identifier.
 * @param {import('three').Box3|null} localBounds Optional local bounding box for procedural fallback.
 * @returns {Array<{ name: string, pos: [number, number, number] }>}
 */
export function getModuleSnapPoints(macroName, localBounds = null) {
  if (!macroName) return [];
  const rawKey = macroName.toLowerCase().trim();
  const baseKey = rawKey.replace(/_macro$/, '');

  // 1. Direct lookup
  let found = SNAP_POINTS_DB[rawKey] || SNAP_POINTS_DB[baseKey] || SNAP_POINTS_DB[baseKey + '_macro'];

  // 2. Defense vs defence spelling normalization
  if (!found) {
    const altKey = baseKey.includes('defense_') 
      ? baseKey.replace('defense_', 'defence_') 
      : baseKey.replace('defence_', 'defense_');
    found = SNAP_POINTS_DB[altKey] || SNAP_POINTS_DB[altKey + '_macro'];
  }

  // 3. Faction generic fallback (e.g. struct_spl_cross_01 -> struct_arg_cross_01)
  if (!found) {
    const factions = ['_arg_', '_tel_', '_par_', '_spl_', '_ter_', '_bor_'];
    for (const fac of factions) {
      if (baseKey.includes(fac)) {
        for (const altFac of factions) {
          if (fac === altFac) continue;
          const altMacro = baseKey.replace(fac, altFac);
          if (SNAP_POINTS_DB[altMacro] || SNAP_POINTS_DB[altMacro + '_macro']) {
            found = SNAP_POINTS_DB[altMacro] || SNAP_POINTS_DB[altMacro + '_macro'];
            break;
          }
        }
      }
      if (found) break;
    }
  }

  // 4. Substring search in DB
  if (!found) {
    for (const dbKey in SNAP_POINTS_DB) {
      const dbBase = dbKey.replace(/_macro$/, '');
      if (dbBase.includes(baseKey) || baseKey.includes(dbBase)) {
        found = SNAP_POINTS_DB[dbKey];
        break;
      }
    }
  }

  if (found && found.length > 0) {
    return found;
  }

  // 5. Fallback from local bounds if available
  if (localBounds && localBounds.getSize && localBounds.getCenter) {
    const size = localBounds.getSize(new (localBounds.min.constructor)());
    const center = localBounds.getCenter(new (localBounds.min.constructor)());
    return [
      { name: 'con_snap_px', pos: [center.x + size.x * 0.5, center.y, center.z] },
      { name: 'con_snap_nx', pos: [center.x - size.x * 0.5, center.y, center.z] },
      { name: 'con_snap_py', pos: [center.x, center.y + size.y * 0.5, center.z] },
      { name: 'con_snap_ny', pos: [center.x, center.y - size.y * 0.5, center.z] },
      { name: 'con_snap_pz', pos: [center.x, center.y, center.z + size.z * 0.5] },
      { name: 'con_snap_nz', pos: [center.x, center.y, center.z - size.z * 0.5] }
    ];
  }

  return [];
}
